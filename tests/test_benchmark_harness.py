"""
tests/test_benchmark_harness.py

Tests scripts/run_benchmark.py's own logic (agreement calculation, hit-
rate calculation, the cost-reduction derivation) using FakeEmbedder --
fast, no network, no dependency on the real bge-small ONNX model
(NFR-09). This is a test of the harness's correctness, separate from
what a real run against FastEmbedEmbedder actually measures (that's
docs/BENCHMARK_REPORT.md's job, generated by running the script for
real -- see its own header for why FakeEmbedder isn't used there).
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

from engine.intelligence.tests.fakes import FakeEmbedder

# scripts/ isn't a package (no __init__.py, matching Track A's existing
# scripts/validate_draft_pairs.py and scripts/benchmark_acceleration.py
# convention), so it's loaded by path rather than a normal import.
_SPEC = importlib.util.spec_from_file_location(
    "run_benchmark", Path(__file__).parent.parent / "scripts" / "run_benchmark.py"
)
run_benchmark = importlib.util.module_from_spec(_SPEC)
sys.modules["run_benchmark"] = run_benchmark
_SPEC.loader.exec_module(run_benchmark)


def test_reference_queries_file_exists_and_is_well_formed() -> None:
    queries = run_benchmark._load_jsonl(run_benchmark.REFERENCE_QUERIES_PATH)
    assert len(queries) > 0
    for row in queries:
        assert "query" in row
        assert row["expected_tier"] in ("local", "cloud_byok", "cascade_cloud")


def test_cache_paraphrase_pairs_file_exists_and_is_well_formed() -> None:
    pairs = run_benchmark._load_jsonl(run_benchmark.CACHE_PARAPHRASE_PAIRS_PATH)
    assert len(pairs) > 0
    for row in pairs:
        assert "original" in row
        assert "paraphrase" in row


def test_reference_queries_are_disjoint_from_training_bootstrap() -> None:
    """The held-out set must not overlap with the router's own training data, or "agreement" would just be training accuracy."""
    from engine.intelligence.router.coldstart_data import BOOTSTRAP_EXAMPLES

    training_queries = {e.query for e in BOOTSTRAP_EXAMPLES}
    reference_queries = {row["query"] for row in run_benchmark._load_jsonl(run_benchmark.REFERENCE_QUERIES_PATH)}
    assert training_queries.isdisjoint(reference_queries)


def test_measure_router_agreement_computes_correct_rate() -> None:
    result = run_benchmark.measure_router_agreement(FakeEmbedder())
    assert result["total"] > 0
    assert 0.0 <= result["agreement_rate"] <= 1.0
    assert result["correct"] == sum(1 for r in result["per_query_results"] if r["correct"])


def test_measure_cache_hit_rate_exact_duplicates_always_hit(tmp_path: Path) -> None:
    result = run_benchmark.measure_cache_hit_rate(FakeEmbedder(), tmp_path / "bench.sqlite3")
    assert result["total_pairs"] > 0
    assert result["exact_duplicate_hit_rate"] == 1.0  # writing then reading the same query always hits


def test_estimate_cost_reduction_matches_local_fraction() -> None:
    router_result = {
        "total": 4,
        "per_query_results": [
            {"predicted": "local", "expected": "local", "confidence": 0.9, "correct": True, "query": "a"},
            {"predicted": "local", "expected": "local", "confidence": 0.9, "correct": True, "query": "b"},
            {"predicted": "cloud_byok", "expected": "cloud_byok", "confidence": 0.9, "correct": True, "query": "c"},
            {"predicted": "cascade_cloud", "expected": "cascade_cloud", "confidence": 0.9, "correct": True, "query": "d"},
        ],
    }
    result = run_benchmark.estimate_cost_reduction(router_result)
    assert result["local_resolved_fraction"] == 0.5
    assert result["projected_cost_reduction_vs_pure_cloud"] == 0.5
    # Must not silently fold in a cache contribution -- see the function's own docstring.
    assert "does not include a cache contribution" in result["note"].lower()
